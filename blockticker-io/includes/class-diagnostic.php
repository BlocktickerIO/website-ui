<?php
/**
 * BT_Diagnostic — single-page truth layer for "did my changes actually ship?"
 *
 * Runs FIVE layers of checks on the live site and reports each independently.
 * Built specifically because the v32/33/34 ship cycle produced no visible
 * change despite plugin-version bumps reporting current. We need to know,
 * objectively, where the disconnect is.
 *
 * Layer 1 — FILE: are the modified source files actually on disk?
 * Layer 2 — TEMPLATE: which template is rendering each known page?
 * Layer 3 — CSS LOAD: which stylesheets are enqueued + actual file contents on disk?
 * Layer 4 — CSS CASCADE: dequeue events that strip our stylesheets
 * Layer 5 — RENDER OUTPUT: actual HTML markup for known fragments
 *
 * Access:
 *   WP Admin → BlockTicker → Diagnostic (admin-only, manage_options capability)
 *   OR
 *   /?bt-diagnose=1 with ?bt-diag-key=<random-key-shown-in-admin>
 *
 * Output is self-contained HTML with copy-to-clipboard so admins can paste
 * the entire report back to engineering.
 *
 * @since v119.28.36
 * @package BlockTicker
 */

if ( ! defined( 'ABSPATH' ) ) exit;

class BT_Diagnostic {

    const NONCE_KEY = 'bt_diag_nonce';
    const DIAG_KEY_OPTION = 'bt_diag_access_key';

    public static function init() {
        // Admin-only menu page
        add_action( 'admin_menu', array( __CLASS__, 'register_admin_page' ), 30 );

        // URL-token access for support / engineering (read-only key in option,
        // rotates on demand from admin). Allows pasting a one-shot URL to a
        // collaborator to see the report without granting admin login.
        add_action( 'init', array( __CLASS__, 'maybe_render_url_token' ), 1 );
    }

    public static function register_admin_page() {
        add_submenu_page(
            'blockticker',
            'Diagnostic',
            'Diagnostic',
            'manage_options',
            'bt-diagnostic',
            array( __CLASS__, 'render_admin_page' )
        );
    }

    /**
     * Public-URL render — only fires when ?bt-diagnose=1 is in the URL AND
     * a valid bt-diag-key is provided. The key is regenerated by clicking
     * "Rotate access key" in the admin UI.
     */
    public static function maybe_render_url_token() {
        if ( empty( $_GET['bt-diagnose'] ) ) return;
        $provided = sanitize_text_field( wp_unslash( $_GET['bt-diag-key'] ?? '' ) );
        $stored = get_option( self::DIAG_KEY_OPTION, '' );
        if ( ! $stored || ! hash_equals( $stored, $provided ) ) return;

        // Authorized — render the diagnostic and exit.
        nocache_headers();
        header( 'Content-Type: text/html; charset=UTF-8' );
        echo '<!DOCTYPE html><html><head><meta charset="utf-8"><title>BlockTicker Diagnostic</title>';
        self::render_inline_css();
        echo '</head><body class="bt-diag-page">';
        echo '<div class="bt-diag-banner">URL-token diagnostic · admin authentication bypassed via key</div>';
        self::render_report();
        echo '</body></html>';
        exit;
    }

    public static function render_admin_page() {
        if ( ! current_user_can( 'manage_options' ) ) {
            wp_die( 'Insufficient permissions.' );
        }

        // Handle key-rotation action
        if ( ! empty( $_POST['bt_diag_rotate'] ) && check_admin_referer( self::NONCE_KEY ) ) {
            $new_key = wp_generate_password( 32, false, false );
            update_option( self::DIAG_KEY_OPTION, $new_key, false );
            echo '<div class="notice notice-success"><p>Access key rotated.</p></div>';
        }

        $diag_key = get_option( self::DIAG_KEY_OPTION, '' );
        if ( empty( $diag_key ) ) {
            $diag_key = wp_generate_password( 32, false, false );
            update_option( self::DIAG_KEY_OPTION, $diag_key, false );
        }

        $url_token_url = add_query_arg(
            array( 'bt-diagnose' => '1', 'bt-diag-key' => $diag_key ),
            home_url( '/' )
        );

        ?>
        <div class="wrap">
            <h1>BlockTicker Diagnostic</h1>
            <p>Five layers of truth-checking for "did my changes actually ship?" Each layer reports independently — read top to bottom, the first layer that fails is where the disconnect is.</p>

            <details style="margin:16px 0;background:#fff;border:1px solid #dcdcde;padding:8px 12px">
                <summary style="cursor:pointer;font-weight:600">Share with engineering (URL-token access)</summary>
                <p style="margin-top:12px">Paste this URL to a collaborator and they can see the same diagnostic without admin login. Anyone with the URL has read-only access to the report — rotate the key to invalidate.</p>
                <p><code style="word-break:break-all;display:block;background:#f6f7f7;padding:8px;border:1px solid #dcdcde;font-size:11px"><?php echo esc_html( $url_token_url ); ?></code></p>
                <form method="post">
                    <?php wp_nonce_field( self::NONCE_KEY ); ?>
                    <button type="submit" name="bt_diag_rotate" value="1" class="button">Rotate access key (invalidates old URL)</button>
                </form>
            </details>

            <div style="background:#fff;border:1px solid #dcdcde;padding:0">
                <?php self::render_inline_css(); ?>
                <div class="bt-diag-page">
                    <?php self::render_report(); ?>
                </div>
            </div>
        </div>
        <?php
    }

